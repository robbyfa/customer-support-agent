def get_dataset() -> list[dict[str, Any]]:
    """Return the full evaluation dataset."""
    return EVAL_DATASET


def get_by_category(category: str) -> list[dict[str, Any]]:
    """Return eval cases matching a specific expected category."""
    return [c for c in EVAL_DATASET if c["expected_category"] == category]


def get_by_expected_review(requires_review: bool) -> list[dict[str, Any]]:
    """Return eval cases by whether human review is expected."""
    return [c for c in EVAL_DATASET if c["expected_human_review"] == requires_review]
